let currentLang = 'ua';
try { currentLang = localStorage.getItem('motty_lang') || 'ua'; } catch(e) {}

function t(key) {
  return (I18N[currentLang] || I18N.ua)[key] || key;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('motty_lang', lang);
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (el.tagName === 'INPUT' && el.placeholder !== undefined) {
      el.placeholder = t(key);
    } else {
      el.innerHTML = t(key);
    }
  });
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });
  document.documentElement.lang = lang;
  // Re-render dynamic parts
  if (typeof Catalog !== 'undefined' && typeof Catalog.rerenderText === 'function') {
    Catalog.rerenderText();
  }
}
